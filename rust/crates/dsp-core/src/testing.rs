fn bytes(hex: &str) -> Vec<u8> {
    hex_to_bytes(hex).expect("captured hex is valid")
}

/// Payload of every chunk of [CONFIG_DUMP_FRAMES] (bytes between sub-index and
/// footer), indexed by sub-index.
pub fn captured_config_chunks() -> Vec<Vec<u8>> {
    CONFIG_DUMP_FRAMES
        .iter()
        .map(|hex| {
            let frame = bytes(hex);
            frame[7..frame.len() - 3].to_vec()
        })
        .collect()
}

/// Config chunks (0x24 responses) contained in [CAPTURED_SESSION_408], i.e.
/// the dump of the preset "Test", indexed by sub-index.
pub fn captured_test_preset_chunks() -> Vec<Vec<u8>> {
    let mut chunks = BTreeMap::new();
    for hex in CAPTURED_SESSION_408 {
        let frame = bytes(hex);
        if frame[2] == 0x01 && frame[5] == 0x24 {
            chunks.insert(frame[6], frame[7..5 + frame[4] as usize].to_vec());
        }
    }
    chunks.into_values().collect()
}

/// All captured frames, decoded.
pub fn captured_frames() -> Vec<Vec<u8>> {
    CONFIG_DUMP_FRAMES.iter().chain(CAPTURED_SESSION_408.iter()).map(|h| bytes(h)).collect()
}
